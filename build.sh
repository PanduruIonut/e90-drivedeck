#!/bin/bash
# Builds and platform-signs DriveDeck. No Gradle: aapt2 + javac + d8 + apksigner.
set -euo pipefail
cd "$(dirname "$0")"

SDK=/opt/homebrew/share/android-commandlinetools
BT=$SDK/build-tools/35.0.0
AJ=$SDK/platforms/android-34/android.jar
EXPECTED_SHA1="27196e386b875e76adf700e7ea84e4c6eee33dfa"   # this head unit's platform cert

rm -rf build && mkdir -p build/stubs build/classes build/dex build/gen/dev/drivedeck

# Third-party jars packaged into the app: Spotify App Remote SDK (classes.jar of the AAR, which has
# no resources) and the Gson it needs.
LIBS="libs/appremote/classes.jar:libs/gson-2.10.1.jar"
[ -f libs/appremote/classes.jar ] || unzip -q -o libs/spotify-app-remote-release-0.8.0.aar classes.jar -d libs/appremote

# Spotify client ID (not a secret, but kept out of git): spotify-client-id.txt -> SpotifyConfig.
CID=$(tr -d '[:space:]' < spotify-client-id.txt 2>/dev/null || true)
[[ "$CID" =~ ^[0-9a-f]{32}$ ]] || { echo "FAIL: spotify-client-id.txt missing or not 32 hex chars" >&2; exit 1; }
printf 'package dev.drivedeck;\n\n/** Generated by build.sh from spotify-client-id.txt. */\nfinal class SpotifyConfig {\n    static final String CLIENT_ID = "%s";\n    static final String REDIRECT_URI = "drivedeck://spotify-auth";\n    private SpotifyConfig() {}\n}\n' "$CID" \
    > build/gen/dev/drivedeck/SpotifyConfig.java

"$BT/aapt2" link --manifest AndroidManifest.xml -I "$AJ" \
    --min-sdk-version 27 --target-sdk-version 27 -o build/base.apk

# Hidden-API stubs: compiled for linking only, never packaged.
javac -source 1.8 -target 1.8 -nowarn -classpath "$AJ" -d build/stubs \
    $(find stubs -name '*.java')
javac -source 1.8 -target 1.8 -nowarn -classpath "$AJ:build/stubs:$LIBS" -d build/classes \
    $(find src build/gen -name '*.java')

"$BT/d8" --min-api 27 --lib "$AJ" --classpath build/stubs --output build/dex \
    $(find build/classes -name '*.class') libs/appremote/classes.jar libs/gson-2.10.1.jar

cp build/base.apk build/unsigned.apk
(cd build/dex && zip -q -j ../unsigned.apk classes.dex)
"$BT/zipalign" -f -p 4 build/unsigned.apk build/aligned.apk
"$BT/apksigner" sign --key keys/platform.pk8 --cert keys/platform.x509.pem \
    --out build/drivedeck.apk build/aligned.apk

got=$("$BT/apksigner" verify --print-certs build/drivedeck.apk \
      | awk -F': ' '/SHA-1 digest/{print $2; exit}')
if [ "$got" != "$EXPECTED_SHA1" ]; then
    echo "FAIL: signed with $got, expected $EXPECTED_SHA1" >&2
    exit 1
fi
echo "OK: build/drivedeck.apk signed with the head unit's platform cert ($got)"
